#!/usr/bin/env python3
"""Generates lib/core/theme/hiwiski_symbols.dart from the Material Symbols metadata file.

The codepoints are generated as `const IconData` and not built dynamically from an
`int`: `--tree-shake-icons` only works with constant `IconData`.

**Only the symbols the source tree actually uses are generated.** That is not thrift
but necessity: Flutter's `const_finder` reads the constants from the kernel and finds
even those nobody points to. With all 4299 symbols in the repository, the font shrank
from 15.2 MB to 15.0 MB in the web build -- that is, not at all. With this selection a
few kilobytes remain.

Whoever needs a new symbol writes `HiwiskiSymbols.<name>` and runs the script again.
Until then the analyzer reports an unknown name -- that is the hint, and it comes by
itself.

Usage:  python3 tool/generate_symbols.py
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "material_symbols_rounded.codepoints"
TARGET = HERE.parent / "lib" / "core" / "theme" / "hiwiski_symbols.dart"

DART_KEYWORDS = {
    "abstract", "as", "assert", "async", "await", "break", "case", "catch", "class",
    "const", "continue", "covariant", "default", "deferred", "do", "dynamic", "else",
    "enum", "export", "extends", "extension", "external", "factory", "false", "final",
    "finally", "for", "function", "get", "hide", "if", "implements", "import", "in",
    "interface", "is", "late", "library", "mixin", "new", "null", "on", "operator",
    "part", "required", "rethrow", "return", "set", "show", "static", "super", "switch",
    "sync", "this", "throw", "true", "try", "typedef", "var", "void", "while", "with",
    "yield",
}


def dart_name(raw: str) -> str:
    parts = re.split(r"[_\s]+", raw)
    name = parts[0] + "".join(p.capitalize() for p in parts[1:])
    if name and name[0].isdigit():
        name = "n" + name
    if name in DART_KEYWORDS:
        name += "Symbol"
    return name


def used_names() -> set[str]:
    """All `HiwiskiSymbols.<name>` from the source tree -- without the generated file itself."""
    lib = HERE.parent / "lib"
    pattern = re.compile(r"HiwiskiSymbols\.([A-Za-z][A-Za-z0-9]*)")
    names: set[str] = set()
    for path in lib.rglob("*.dart"):
        if path == TARGET:
            continue
        names.update(pattern.findall(path.read_text()))
    names.discard("fontFamily")
    return names


def main() -> None:
    wanted = used_names()
    seen: dict[str, str] = {}
    for line in SOURCE.read_text().splitlines():
        if not line.strip():
            continue
        raw, codepoint = line.split()
        name = dart_name(raw)
        if name not in wanted:
            continue
        # First one wins: the file occasionally contains aliases for the same codepoint.
        seen.setdefault(name, codepoint)

    lines = [
        "// GENERATED by tool/generate_symbols.py -- do not edit by hand.",
        "//",
        "// Material Symbols Rounded as a variable font in the repository, not Flutter's",
        "// built-in `Icons`. The built-in ones are *Material Icons* -- a different set,",
        "// without the FILL, wght, GRAD, opsz axes, and without the rounded variant",
        "//.",
        "//",
        "// Only the symbols the source tree uses: Flutter's const_finder reads the",
        "// constants from the kernel and finds even those nobody points to there --",
        "// with all 4299 the font did not shrink at all in the web build. A new",
        "// symbol is added via `python3 tool/generate_symbols.py`.",
        "//",
        "// FILL 0 at rest, FILL 1 for selected. That is the only state indicator on a",
        "// symbol in the whole design -- in Flutter `fill: 0` or `fill: 1`, not two",
        "// different icons. That needs the variable font: with a static variant",
        "// `fill: 1` does nothing, without any error message.",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// The app's symbol set.",
        "abstract final class HiwiskiSymbols {",
        "  /// The font's family name, as it appears in `pubspec.yaml`.",
        "  static const String fontFamily = 'MaterialSymbolsRounded';",
        "",
    ]
    for name, codepoint in sorted(seen.items()):
        lines.append(
            f"  static const IconData {name} = "
            f"IconData(0x{codepoint}, fontFamily: fontFamily);"
        )
    lines.append("}")
    lines.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))
    missing = wanted - set(seen)
    if missing:
        print("not in the metadata file: " + ", ".join(sorted(missing)))
    print(f"{TARGET}: {len(seen)} of {len(wanted)} used symbols")


if __name__ == "__main__":
    main()
